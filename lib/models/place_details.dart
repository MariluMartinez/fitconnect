class PlaceDetails {
  final String placeId;
  final String name;
  final String city;
  final String state;
  final double latitude;
  final double longitude;

  const PlaceDetails({
    required this.placeId,
    required this.name,
    required this.city,
    required this.state,
    required this.latitude,
    required this.longitude,
  });
}